#: Версия формулы squeeze_index. Пишется в журнал при каждом расчёте: без неё
#: после первой калибровки весов история станет несопоставимой (PLAN §4.11).
#:
#: v2 (02.09.2026): группа «диапазон» переведена с абсолютного порога ширины на
#: перцентиль по собственной истории монеты. Измерено, что абсолютный порог
#: давал ровно ноль всем ста двадцати монетам универсума, кроме золотых
#: токенов, — то есть четверть веса формулы простаивала. Записи v1 и v2
#: несопоставимы.
#: v3 (02.09.2026): окно ряда сделано каноническим — метрикам даётся ровно
#: столько свечей, сколько требуют правила §4.2 (360 наблюдений и 60 суток
#: охвата), а не сколько поместилось в страницу ответа. До этого сервер считал
#: по 1500 свечам, а сканер по другому числу, и сезонная база объёма у них
#: расходилась. Формула не менялась, изменилась глубина входа.
#: v4 (03.09.2026): изменено определение бара набора, а он входит в группу
#: «объём» с весом 0.3, то есть в индекс — с весом 0.06. Две правки, обе в
#: §4.25. Первая: окно задаётся календарным сроком (трое суток), а не
#: постоянным числом свечей, — тридцать свечей означали тридцать часов на 1h и
#: тридцать суток на 1d. Для 4h и 1d окно осталось прежним, для 1h выросло с
#: 30 до 72. Вторая: тело «тихой» свечи сравнивается с МАКСИМУМОМ из 0.5 ATR и
#: 0.3% цены — иначе в сжатии порог падает вместе с ATR и признак исчезает
#: ровно там, где нужен.
#:
#: Расхождение с v3 замерено на 67 монетах с оборотом от 10M: на 4h индекс
#: совпал у ВСЕХ до четвёртого знака (баров набора 27 против 27 — вторая
#: правка на нормальном ATR не срабатывает вовсе), на 1h не изменился у 50 из
#: 67, средняя дельта +0.017, максимум +0.15, а баров набора стало 42 против
#: 18. То есть версия поднята почти целиком ради 1h; но записи всё равно
#: несопоставимы, а смешивать поколения в одном ранге нельзя.
#: v5 (04.09.2026): состав свёртки изменён впервые с начала проекта (§4.33).
#: Из формулы убраны `value_area` и `divergence`, освободившиеся 0.20 целиком
#: отданы новой группе `duration` — перцентилю длительности текущего сжатия
#: среди ЗАВЕРШЁННЫХ серий этой же пары. Причина: длительность была
#: единственной метрикой, меряющей время, и на индекс не влияла вовсе, а
#: профиль с дивергенцией вместе давали «бесплатный пол» 0.33, с которого до
#: топ-15 оставалось добрать 0.22 из 0.60.
#:
#: Записи v4 и v5 несопоставимы: у групп изменился и состав, и веса. Старые
#: строки не мигрируются — `get_scan_history` и ранг сравнивают только записи
#: одной версии, а колонка версии входит в уникальный ключ.
#:
#: v6 (15.09.2026): сам `squeeze_index` НЕ изменился — детектор распределения
#: в него не входит и входить не должен, это отдельное измерение, а не шестая
#: группа. Версия поднята по другой причине: `scan_log` пишется через
#: `INSERT OR IGNORE`, строка не переписывается, и восемь новых колонок
#: (`dist_*`, `absorp_*`) остались бы у вчерашних записей пустыми навсегда.
#: Проверять поведение детектора можно только на строках, сделанных ПОСЛЕ
#: выката (SPEC-distribution-detector §7).
#:
#: Цена подъёма известна и штатна: выдача `scan_pairs` без `symbols` и ранги
#: списка наблюдения пустеют примерно на час, пока часовой прогон не напишет
#: строки нового поколения.
